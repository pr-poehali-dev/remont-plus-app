export const CITY_BY_SLUG: Record<string, City> = Object.fromEntries(
  CITIES.map((c) => [c.slug, c]),
);

export function getCity(slug?: string): City | undefined {
  return slug ? CITY_BY_SLUG[slug] : undefined;
}

/** Ближайшие по алфавиту соседи — для блока перелинковки «Другие города». */
export function otherCities(slug: string, limit = 8): City[] {
  const idx = CITIES.findIndex((c) => c.slug === slug);
  if (idx < 0) return CITIES.slice(0, limit);
  const rest = [...CITIES.slice(idx + 1), ...CITIES.slice(0, idx)];
  return rest.slice(0, limit);
}